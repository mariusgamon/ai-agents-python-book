# agent_loop.py
from mistral_raw import llm


def agent_loop(user_input: str, max_turns: int = 8) -> str:
    """
    Minimal agent loop with max_turns protection.

    This simple version doesn't use tools yet: each turn calls the LLM
    with the current history, and we stop as soon as the LLM answers
    "END:" followed by the final answer (an explicit signal).

    Exit logic:
    - The LLM prefixes its answer with "END:" → we return what follows
    - Otherwise, we go again, up to max_turns
    - max_turns reached → we raise an explicit exception

    In B.4, we'll replace the "END:" sentinel with JSON parsing to
    distinguish "tool call" from "final answer" — much more robust.
    """
    messages = [
        {
            "role":    "system",
            "content": (
                "You are an assistant. When you have the final answer, prefix it "
                "with exactly \"END:\" followed by your answer, and nothing else. "
                "If you need more information, ask a single question "
                "(without the \"END:\" prefix)."
            ),
        },
        {"role": "user", "content": user_input},
    ]

    for turn in range(1, max_turns + 1):
        print(f"[Turn {turn}/{max_turns}]")

        response = llm(messages)
        messages.append({"role": "assistant", "content": response})

        # Real exit condition: is the LLM signaling the end?
        if response.strip().startswith("END:"):
            return response.strip()[4:].strip()

        # Otherwise, keep going: the LLM asked a question — we ask it
        # to continue (in real use, we'd inject the user's answer or a
        # tool result here — see B.4).
        messages.append({
            "role": "user",
            "content": "Continue. If you have the answer, prefix it with \"END:\".",
        })

    # If we get here, we've used up all the turns
    raise RuntimeError(
        f"Agent stuck after {max_turns} turns. "
        f"Last message: {messages[-1]['content'][:200]}"
    )


def agent_loop_naive(user_input: str) -> str:
    """
    A truly infinite loop — the exit condition depends on a fragile
    signal the LLM may forget to send.
    """
    messages = [{"role": "user", "content": user_input}]

    while True:                     # unbounded loop — no guardrail
        response = llm(messages)
        messages.append({"role": "assistant", "content": response})

        # Fragile exit condition: we depend on a keyword generated by the LLM.
        # If the model never says "DONE", we loop forever.
        if "DONE" in response:
            return response

        messages.append({
            "role":    "user",
            "content": "Keep going until you're done.",
        })
